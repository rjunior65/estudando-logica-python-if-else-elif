#Treinando conceito if, elif, else

temperatura_computador = float(input('qual a temperatura atual do meu computador: '))

if temperatura_computador >= 90:
     print('computador em estado critico ')
elif temperatura_computador >= 70:
     print('nescessario atenção')
elif temperatura_computador >= 60:
     print('temperatura normal ')
else:
     print('ele esta muito bemmmmmmmmmmm')